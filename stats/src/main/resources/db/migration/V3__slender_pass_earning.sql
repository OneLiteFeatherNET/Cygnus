-- Slender pass earning: the pity counter, the monthly quota marker and the two earned ledger reasons.
--
-- Plain SQL that PostgreSQL and H2 in PostgreSQL mode both accept. V1 and V2 are not changed.

-- Survivor rounds since the last Slender round or the last earned pass. Existing balances start at zero.
ALTER TABLE player_slender_pass
    ADD COLUMN rounds_since_slender INTEGER NOT NULL DEFAULT 0 CHECK (rounds_since_slender >= 0);

-- The calendar month ('YYYY-MM', UTC) of the last monthly quota, empty until the first grant.
ALTER TABLE player_slender_pass
    ADD COLUMN last_quota_month VARCHAR(7);

-- The reason check of V2 is unnamed, and PostgreSQL and H2 name such a constraint differently, so it cannot be
-- dropped by name on both. The ledger is rebuilt instead: the rows are copied in their order. The ids are
-- renumbered, because the identity column of PostgreSQL does not move past ids that were written explicitly, and
-- nothing refers to a ledger id.
CREATE TABLE slender_pass_transaction_v3 (
    id          BIGINT                   GENERATED BY DEFAULT AS IDENTITY,
    player_uuid UUID                     NOT NULL,
    delta       INTEGER                  NOT NULL,
    reason      VARCHAR(16)              NOT NULL,
    round_id    UUID,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_slender_pass_transaction_reason CHECK (reason IN
        ('ADMIN_GIVE', 'ADMIN_TAKE', 'ADMIN_SET', 'REDEEM', 'EARNED_PITY', 'RANK_QUOTA'))
);

INSERT INTO slender_pass_transaction_v3 (player_uuid, delta, reason, round_id, created_at)
SELECT player_uuid, delta, reason, round_id, created_at
FROM slender_pass_transaction
ORDER BY id;

DROP TABLE slender_pass_transaction;

ALTER TABLE slender_pass_transaction_v3 RENAME TO slender_pass_transaction;

-- The rows of one player, for the GDPR deletion and for reading the history (same as V2).
CREATE INDEX idx_slender_pass_transaction_player ON slender_pass_transaction (player_uuid);
