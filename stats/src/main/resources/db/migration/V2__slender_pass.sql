-- Slender passes: one balance per player and an append-only ledger of every change.
--
-- Plain SQL that PostgreSQL and H2 in PostgreSQL mode both accept, the same as V1. The balance never goes
-- below zero (CHECK), and every change writes one ledger row in the same transaction.

-- One balance per player. version is the optimistic lock two servers writing the same balance rely on.
CREATE TABLE player_slender_pass (
    player_uuid UUID    NOT NULL,
    balance     INTEGER NOT NULL CHECK (balance >= 0),
    version     BIGINT  NOT NULL,
    PRIMARY KEY (player_uuid)
);

-- The ledger. delta is the change that was really written, reason says why, round_id is set for REDEEM only.
CREATE TABLE slender_pass_transaction (
    id          BIGINT                   GENERATED BY DEFAULT AS IDENTITY,
    player_uuid UUID                     NOT NULL,
    delta       INTEGER                  NOT NULL,
    reason      VARCHAR(16)              NOT NULL,
    round_id    UUID,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_slender_pass_transaction_reason CHECK (reason IN ('ADMIN_GIVE', 'ADMIN_TAKE', 'ADMIN_SET', 'REDEEM'))
);

-- The rows of one player, for the GDPR deletion and for reading the history.
CREATE INDEX idx_slender_pass_transaction_player ON slender_pass_transaction (player_uuid);
